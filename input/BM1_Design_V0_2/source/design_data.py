def export_data():
    (ROOT/'data').mkdir(exist_ok=True)
    design=dict(META,parameters={k:{'value':v,'status':'concept'} for k,v in PARAMS.items()},
        experimental={'rpm_limits':None,'motor_electrical_ratings':None,'wheel_gap_effective':None,
                      'landing_calibration':[],'feather_clearance_dynamic':None,'capacity_verified':None},
        nonmanufacturing=True)
    for name,obj in [('design.json',design),('parts.json',PARTS),('assemblies.json',list(ASM.values())),
                     ('joints.json',JOINTS),('unresolved.json',[dict(id=a,title=b,affected=c,close_condition=d) for a,b,c,d in UNRESOLVED]),
                     ('sources.json',[dict(id=a,title=b,url=c,accessed='2026-10-26') for a,b,c in SOURCES])]:
        (ROOT/'data'/name).write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding='utf-8')

if __name__=='__main__':
    export_data()
    print('parts',len(PARTS))
